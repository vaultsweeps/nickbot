-- Telegram support bot: initial schema.
-- Safe to re-run: tables/indexes use IF NOT EXISTS, functions use CREATE OR REPLACE.
-- All tables have RLS enabled with NO policies, so anon/authenticated get nothing.
-- The server uses the service-role key (which bypasses RLS) and is the only client.

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

-- ---------------------------------------------------------------- customers
create table if not exists public.customers (
  id                 uuid primary key default gen_random_uuid(),
  telegram_user_id   bigint not null unique,
  telegram_username  text check (telegram_username is null or telegram_username ~ '^[A-Za-z0-9_]{1,64}$'),
  first_name         text,
  last_name          text,
  phone_number       text check (phone_number is null or phone_number ~ '^\+[0-9]{5,15}$'),
  phone_verified_at  timestamptz,
  phone_shared_at    timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  last_seen_at       timestamptz not null default now()
);

-- ------------------------------------------------------------ conversations
create table if not exists public.conversations (
  id                         uuid primary key default gen_random_uuid(),
  ticket_number              bigint generated by default as identity (start with 1000) unique,
  customer_id                uuid not null references public.customers(id) on delete restrict,
  status                     text not null default 'open' check (status in ('open', 'closed')),
  staff_group_id             bigint not null,
  forum_topic_id             bigint,
  topic_name                 text check (topic_name is null or char_length(topic_name) <= 128),
  topic_creating_at          timestamptz,
  assigned_staff_telegram_id bigint,
  created_at                 timestamptz not null default now(),
  updated_at                 timestamptz not null default now(),
  closed_at                  timestamptz
);

-- One active conversation per customer (drop this index to allow multiple tickets later).
create unique index if not exists conversations_one_open_per_customer
  on public.conversations (customer_id) where status = 'open';
-- A topic belongs to exactly one conversation.
create unique index if not exists conversations_group_topic_uq
  on public.conversations (staff_group_id, forum_topic_id) where forum_topic_id is not null;
create index if not exists conversations_customer_idx
  on public.conversations (customer_id, created_at desc);

drop trigger if exists conversations_set_updated_at on public.conversations;
create trigger conversations_set_updated_at before update on public.conversations
  for each row execute function public.set_updated_at();

drop trigger if exists customers_set_updated_at on public.customers;
create trigger customers_set_updated_at before update on public.customers
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------- messages
-- sender_type: customer | staff | staff_note (internal, never delivered to customers)
create table if not exists public.messages (
  id                      uuid primary key default gen_random_uuid(),
  conversation_id         uuid not null references public.conversations(id) on delete cascade,
  customer_id             uuid not null references public.customers(id) on delete restrict,
  sender_type             text not null check (sender_type in ('customer', 'staff', 'staff_note')),
  sender_telegram_id      bigint,
  sender_username         text,
  telegram_update_id      bigint,
  telegram_chat_id        bigint not null,
  telegram_message_id     bigint not null,
  message_thread_id       bigint,
  reply_to_message_id     bigint,
  message_type            text not null check (message_type in ('text', 'photo', 'video', 'document', 'voice')),
  text_content            text,
  caption                 text,
  telegram_file_id        text,
  telegram_file_unique_id text,
  delivery_status         text not null default 'pending'
                          check (delivery_status in ('pending', 'delivered', 'failed', 'skipped')),
  error_message           text,
  created_at              timestamptz not null default now(),
  delivered_at            timestamptz,
  -- a Telegram message id is unique within its chat: this is the per-message idempotency key
  constraint messages_chat_message_uq unique (telegram_chat_id, telegram_message_id)
);
create index if not exists messages_conversation_idx on public.messages (conversation_id, created_at);
create index if not exists messages_customer_idx on public.messages (customer_id);
create index if not exists messages_update_idx on public.messages (telegram_update_id);
create index if not exists messages_status_idx on public.messages (delivery_status) where delivery_status <> 'delivered';

-- --------------------------------------------------------- message_mappings
-- customer_to_staff: staff_message_id = bot's copy in the topic, customer_message_id = customer's original
-- staff_to_customer: staff_message_id = staff's message in the topic, customer_message_id = bot's copy in the customer chat
create table if not exists public.message_mappings (
  id                  uuid primary key default gen_random_uuid(),
  conversation_id     uuid not null references public.conversations(id) on delete cascade,
  customer_id         uuid not null references public.customers(id) on delete restrict,
  message_id          uuid references public.messages(id) on delete set null,
  staff_group_id      bigint not null,
  forum_topic_id      bigint not null,
  staff_message_id    bigint not null,
  customer_chat_id    bigint not null,
  customer_message_id bigint not null,
  mapping_type        text not null check (mapping_type in ('customer_to_staff', 'staff_to_customer')),
  created_at          timestamptz not null default now(),
  constraint message_mappings_group_message_uq unique (staff_group_id, staff_message_id)
);
create index if not exists message_mappings_customer_idx
  on public.message_mappings (customer_chat_id, customer_message_id);
create index if not exists message_mappings_conversation_idx on public.message_mappings (conversation_id);
create index if not exists message_mappings_topic_idx on public.message_mappings (staff_group_id, forum_topic_id);

-- ---------------------------------------------------------- telegram_updates
-- Doubles as the idempotency table AND the durable retry queue: the raw update is stored,
-- and failed updates are re-run (every step is itself idempotent) by Telegram redelivery
-- or by the /api/cron/retry sweeper.
create table if not exists public.telegram_updates (
  update_id       bigint primary key,
  status          text not null default 'processing'
                  check (status in ('processing', 'processed', 'failed', 'dead')),
  attempt_count   integer not null default 0,
  last_error      text,
  payload         jsonb,
  locked_at       timestamptz,
  next_attempt_at timestamptz,
  received_at     timestamptz not null default now(),
  processed_at    timestamptz
);
create index if not exists telegram_updates_retry_idx
  on public.telegram_updates (status, next_attempt_at) where status in ('failed', 'processing');
create index if not exists telegram_updates_received_idx on public.telegram_updates (received_at);

-- --------------------------------------------------------------- functions
-- Atomically fetch / create / reopen the customer's conversation.
create or replace function public.ensure_conversation(p_customer_id uuid, p_staff_group_id bigint)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
  c public.conversations;
  v_created boolean := false;
  v_reopened boolean := false;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_customer_id::text, 0));

  select * into c from public.conversations
   where customer_id = p_customer_id order by created_at desc limit 1;

  if not found then
    insert into public.conversations (customer_id, staff_group_id)
    values (p_customer_id, p_staff_group_id) returning * into c;
    v_created := true;
  else
    if c.status = 'closed' then
      update public.conversations set status = 'open', closed_at = null
       where id = c.id returning * into c;
      v_reopened := true;
    end if;
    if c.staff_group_id <> p_staff_group_id then
      -- staff group was replaced: the old topic id is meaningless in the new group
      update public.conversations
         set staff_group_id = p_staff_group_id, forum_topic_id = null, topic_name = null, topic_creating_at = null
       where id = c.id returning * into c;
    end if;
  end if;

  return jsonb_build_object('conversation', to_jsonb(c), 'created', v_created, 'reopened', v_reopened);
end $$;

-- Only one caller wins the right to create the topic (lock expires after p_lock_seconds).
create or replace function public.claim_topic_creation(p_conversation_id uuid, p_lock_seconds integer default 30)
returns boolean
language plpgsql
set search_path = public
as $$
declare v_id uuid;
begin
  update public.conversations
     set topic_creating_at = now()
   where id = p_conversation_id
     and forum_topic_id is null
     and (topic_creating_at is null or topic_creating_at < now() - make_interval(secs => p_lock_seconds))
  returning id into v_id;
  return v_id is not null;
end $$;

-- Idempotent claim of a webhook update. Returns: claimed | duplicate | in_progress | dead
-- plus the attempt number, so the caller can apply backoff.
create or replace function public.claim_telegram_update(
  p_update_id bigint, p_payload jsonb,
  p_lock_seconds integer default 120, p_max_attempts integer default 8)
returns jsonb
language plpgsql
set search_path = public
as $$
declare r public.telegram_updates;
begin
  insert into public.telegram_updates (update_id, payload, status, attempt_count, locked_at)
  values (p_update_id, p_payload, 'processing', 1, now())
  on conflict (update_id) do nothing;
  if found then
    return jsonb_build_object('result', 'claimed', 'attempt', 1);
  end if;

  select * into r from public.telegram_updates where update_id = p_update_id for update;
  if r.status = 'processed' then
    return jsonb_build_object('result', 'duplicate', 'attempt', r.attempt_count);
  end if;
  if r.status = 'dead' then
    return jsonb_build_object('result', 'dead', 'attempt', r.attempt_count);
  end if;
  if r.status = 'processing' and r.locked_at > now() - make_interval(secs => p_lock_seconds) then
    return jsonb_build_object('result', 'in_progress', 'attempt', r.attempt_count);
  end if;
  if r.attempt_count >= p_max_attempts then
    update public.telegram_updates set status = 'dead' where update_id = p_update_id;
    return jsonb_build_object('result', 'dead', 'attempt', r.attempt_count);
  end if;

  update public.telegram_updates
     set status = 'processing', attempt_count = attempt_count + 1, locked_at = now(),
         payload = coalesce(payload, p_payload)
   where update_id = p_update_id
  returning * into r;
  return jsonb_build_object('result', 'claimed', 'attempt', r.attempt_count);
end $$;

-- ---------------------------------------------------------------- security
alter table public.customers        enable row level security;
alter table public.conversations    enable row level security;
alter table public.messages         enable row level security;
alter table public.message_mappings enable row level security;
alter table public.telegram_updates enable row level security;

-- Deny by default: no policies are created, and API roles get no table or function privileges.
revoke all on public.customers, public.conversations, public.messages,
              public.message_mappings, public.telegram_updates from anon, authenticated;
revoke all on function public.ensure_conversation(uuid, bigint) from public, anon, authenticated;
revoke all on function public.claim_topic_creation(uuid, integer) from public, anon, authenticated;
revoke all on function public.claim_telegram_update(bigint, jsonb, integer, integer) from public, anon, authenticated;
grant execute on function public.ensure_conversation(uuid, bigint) to service_role;
grant execute on function public.claim_topic_creation(uuid, integer) to service_role;
grant execute on function public.claim_telegram_update(bigint, jsonb, integer, integer) to service_role;
